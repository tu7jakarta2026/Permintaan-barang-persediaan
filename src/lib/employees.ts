export function isAuthorizedToSeeAll(employee: Employee | null | undefined): boolean {
  if (!employee) return false;
  const nrk = employee.nrk.trim();
  const nameLower = employee.name.toLowerCase();
  
  // Authorized NRK list:
  // 187281: Turimin, S.Pd
  // 222538: Maya Permatasari Rezeki, S.Ak
  // 189128: Dwi Ratih Ryansari
  // 1025366: Sunaryo
  const authorizedNrks = ["187281", "222538", "189128", "1025366"];
  if (authorizedNrks.includes(nrk)) {
    return true;
  }
  
  // Alternative substring name check for maximum robustness
  if (
    nameLower.includes("turimin") ||
    nameLower.includes("maya permatasari") ||
    nameLower.includes("dwi ratih") ||
    nameLower.includes("sunaryo")
  ) {
    return true;
  }
  
  return false;
}

